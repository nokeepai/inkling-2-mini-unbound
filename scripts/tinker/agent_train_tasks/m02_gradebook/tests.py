import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from solution import *
book = {"ann": [90, 95, 100], "bob": [70, 80], "cat": [95, 95, 95], "dan": [50, 40, 61]}
assert mean([]) == 0.0, "mean of empty"
assert mean([1, 2, 3]) == 2, "mean"
assert median([3, 1, 2]) == 2.0, "median odd"
assert median([4, 1, 3, 2]) == 2.5, "median even"
assert median([]) == 0.0, "median empty"
assert letter(90) == "A", "A boundary"
assert letter(89.9) == "B", "just below A"
assert letter(60) == "D", "D boundary"
assert letter(59) == "F", "F"
assert drop_lowest([5, 1, 3]) == [3, 5], "drop lowest"
assert drop_lowest([5], 1) == [5], "never drop all"
assert drop_lowest([5, 1, 3], 0) == [5, 1, 3], "drop none"
assert weighted_average([80, 90], [1, 3]) == 87.5, "weighted average"
assert weighted_average([80], [0]) == 0.0, "zero weight"
assert curve([70, 85, 90]) == [80, 95, 100], "curve"
assert curve([]) == [], "curve empty"
assert rank(book) == ["ann", "cat", "bob", "dan"], "rank with tie"
assert distribution(book) == {"A": 2, "B": 0, "C": 1, "D": 0, "F": 1}, "distribution"
assert honor_roll(book) == ["ann", "cat"], "honor roll"
assert honor_roll(book, 95) == ["ann", "cat"], "honor roll at exact threshold"
assert honor_roll(book, 96) == [], "honor roll none"
assert most_improved(book) == "dan", "most improved"
assert most_improved({"x": [5]}) is None, "most improved needs two scores"
