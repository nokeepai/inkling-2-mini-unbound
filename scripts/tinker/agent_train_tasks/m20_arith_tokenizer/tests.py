import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from solution import *
assert tokenize("") == [], "empty input"
assert tokenize("1+2") == [("NUM", "1"), ("OP", "+"), ("NUM", "2")], "simple sum"
assert tokenize("3.14*r**2") == [("NUM", "3.14"), ("OP", "*"), ("ID", "r"), ("OP", "**"), ("NUM", "2")], "power operator"
assert tokenize(".5") == [("NUM", ".5")], "leading dot number"
assert tokenize("1.2.3") == [("NUM", "1.2"), ("NUM", ".3")], "second dot starts new number"
assert tokenize("x_1 >= 10") == [("ID", "x_1"), ("OP", ">="), ("NUM", "10")], "two-char comparison"
assert tokenize("a<b") == [("ID", "a"), ("OP", "<"), ("ID", "b")], "single-char comparison"
t = tokenize("-(a + (b - 2)) * -c")
assert len(t) == 13, "token count"
assert t[0] == ("OP", "-"), "leading minus"
assert balanced(t) == True, "balanced"
assert balanced(tokenize("(1))(")) == False, "closing too early"
assert balanced(tokenize("((1)")) == False, "unclosed"
assert max_depth(t) == 2, "max depth"
assert max_depth([]) == 0, "depth of nothing"
assert mark_unary(t)[0] == ("OP", "U-"), "unary at start"
assert mark_unary(t)[6] == ("OP", "-"), "binary minus after identifier"
assert mark_unary(t)[11] == ("OP", "U-"), "unary after operator"
assert identifiers(t) == ["a", "b", "c"], "identifiers"
assert identifiers(tokenize("x+x*y")) == ["x", "y"], "identifiers deduplicated"
assert read_number("12ab", 0) == ("12", 2), "read number stops at letter"
assert read_ident("ab_9+", 0) == ("ab_9", 4), "read identifier"
