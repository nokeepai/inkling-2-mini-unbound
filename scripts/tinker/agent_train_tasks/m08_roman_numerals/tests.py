assert add("XIV", "VI") == "XX", "add"
assert subtract("X", "I") == "IX", "subtract"
assert longest_numeral(10) == 8, "longest up to ten"
assert longest_numeral(1) == 1, "longest up to one"
assert count_symbols("MMXX") == {"M": 2, "X": 2}, "count symbols"
assert max_repeat("MMMCX") == 3, "max repeat"
assert max_repeat("") == 0, "max repeat empty"
assert sort_numerals(["X", "IV", "C", "IX"]) == ["IV", "IX", "X", "C"], "sort"
assert numerals_between(3, 5) == ["III", "IV", "V"], "range inclusive"
assert numerals_between(-2, 1) == ["I"], "range clamps low"
