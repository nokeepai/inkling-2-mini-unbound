assert to_roman(1) == "I", "one"
assert to_roman(4) == "IV", "four"
assert to_roman(9) == "IX", "nine"
assert to_roman(1994) == "MCMXCIV", "1994"
assert to_roman(3999) == "MMMCMXCIX", "max"
assert from_roman("MCMXCIV") == 1994, "parse 1994"
assert from_roman("") == 0, "parse empty"
assert from_roman("LVIII") == 58, "parse 58"
assert is_valid("XIV") == True, "valid"
assert is_valid("IIII") == False, "non-canonical"
assert is_valid("") == False, "empty invalid"
