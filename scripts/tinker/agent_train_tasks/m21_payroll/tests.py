import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from solution import *
assert minutes_between("09:00", "17:30") == 510, "day shift"
assert minutes_between("22:00", "06:00") == 480, "overnight shift"
assert shift_minutes("09:00", "17:30", 30) == 480, "with break"
assert shift_minutes("09:00", "09:10", 30) == 0, "break longer than shift"
assert split_week([480] * 5) == (2400, 0), "standard week"
assert split_week([600] * 5) == (2400, 600), "daily overtime"
assert split_week([480] * 6) == (2400, 480), "weekly overtime"
assert split_week([]) == (0, 0), "empty week"
assert split_week([540, 480, 480, 480, 480, 120]) == (2400, 180), "daily and weekly overtime"
assert gross_pay([480] * 5, 2000) == 80000, "gross standard"
assert gross_pay([540], 2000) == 19000, "gross with overtime"
assert income_tax(0) == 0, "no tax"
assert income_tax(50000) == 5000, "top of first bracket"
assert income_tax(100000) == 15000, "second bracket"
assert income_tax(200000) == 40000, "third bracket"
assert net_pay([480] * 5, 2000) == 69000, "net pay"
assert format_hours(485) == "8:05", "format padded minutes"
assert format_hours(0) == "0:00", "format zero"
assert week_from_shifts([("09:00", "17:00", 0), ("08:00", "18:00", 60)]) == [480, 540], "week from shifts"
assert effective_rate([480] * 5, 2000) == 1725, "effective rate"
assert effective_rate([], 2000) == 0, "effective rate no work"
