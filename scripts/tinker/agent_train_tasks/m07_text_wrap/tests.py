import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from solution import *
assert wrap("", 10) == [], "empty text"
assert wrap("the quick brown fox", 10) == ["the quick", "brown fox"], "basic wrap"
assert wrap("aaa bbb", 7) == ["aaa bbb"], "exact fit"
assert wrap("aaa bbb", 6) == ["aaa", "bbb"], "one short of fit"
assert wrap("abcdefgh ij", 3) == ["abc", "def", "gh", "ij"], "long word split"
assert wrap("  spaced   out  ", 20) == ["spaced out"], "collapse spaces"
assert justify_line("a b c", 8) == "a   b  c", "extra space goes left"
assert justify_line("a b c", 9) == "a   b   c", "even spacing"
assert justify_line("word", 6) == "word  ", "single word padded"
assert justify("the quick brown fox", 10) == ["the  quick", "brown fox "], "justify paragraph"
assert justify("", 5) == [], "justify empty"
assert center("ab", 5) == " ab  ", "center odd padding"
assert center("abcdef", 4) == "abcdef", "center too long"
assert truncate("hello world", 8) == "hello...", "truncate"
assert truncate("hello", 5) == "hello", "truncate exact"
assert truncate("hello", 2) == "..", "truncate tiny width"
assert line_count("one two three", 7) == 2, "line count"
assert raggedness(["ab", "abc", "a"], 4) == 5, "raggedness ignores last"
assert raggedness(["x"], 4) == 0, "single line raggedness"
