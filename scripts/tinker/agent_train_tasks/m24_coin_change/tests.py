import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from solution import *
assert greedy_change(0, US_COINS) == {}, "zero amount"
assert greedy_change(41, US_COINS) == {25: 1, 10: 1, 5: 1, 1: 1}, "greedy 41"
assert greedy_change(3, [2]) is None, "greedy cannot finish"
assert min_coins(0, [1]) == 0, "min coins zero"
assert min_coins(6, [1, 3, 4]) == 2, "min coins beats greedy"
assert min_coins(7, [2, 4]) == -1, "impossible amount"
assert min_coins(30, US_COINS) == 2, "quarter plus nickel"
assert optimal_change(6, [1, 3, 4]) == {3: 2}, "optimal change"
assert optimal_change(7, [2, 4]) is None, "optimal impossible"
assert optimal_change(0, [1]) == {}, "optimal zero"
assert count_ways(4, [1, 2, 3]) == 4, "count ways"
assert count_ways(0, [5]) == 1, "one way to make zero"
assert count_ways(3, [2]) == 0, "no ways"
assert count_ways(10, US_COINS) == 4, "ways to make a dime"
assert coin_total({25: 2, 1: 3}) == 53, "coin total"
assert first_greedy_failure([1, 3, 4], 10) == 6, "greedy fails at 6"
assert first_greedy_failure(US_COINS, 100) == 0, "greedy optimal for US coins"
assert first_greedy_failure([4, 3], 6) == 6, "greedy unfinished but possible"
assert make_change_from_till(30, {25: 0, 10: 3}) == {10: 3}, "till without quarters"
assert make_change_from_till(30, {25: 1, 10: 3, 5: 0}) is None, "till greedy fails"
assert make_change_from_till(0, {5: 1}) == {}, "till zero amount"
